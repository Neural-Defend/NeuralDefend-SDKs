plugins {
    alias(libs.plugins.kotlin.jvm) apply false
    alias(libs.plugins.kotlin.compose) apply false
    alias(libs.plugins.android.library) apply false
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.dokka) apply false
}

val stagingRepository = layout.buildDirectory.dir("staging-deploy")
val sdkVersion = providers.gradleProperty("VERSION_NAME").get()

subprojects {
    group = providers.gradleProperty("GROUP").get()
    version = sdkVersion

    pluginManager.withPlugin("maven-publish") {
        extensions.configure<PublishingExtension> {
            repositories {
                maven {
                    name = "staging"
                    url = uri(stagingRepository)
                }
            }
            publications.withType<MavenPublication>().configureEach {
                pom {
                    url.set("https://github.com/Neural-Defend/NeuralDefend-SDKs/tree/main/packages/kotlin")
                    inceptionYear.set("2026")
                    licenses {
                        license {
                            name.set("MIT License")
                            url.set("https://github.com/Neural-Defend/NeuralDefend-SDKs/blob/main/LICENSE")
                            distribution.set("repo")
                        }
                    }
                    developers {
                        developer {
                            id.set("neuraldefend")
                            name.set("Neural Defend")
                            url.set("https://neuraldefend.com")
                        }
                    }
                    organization {
                        name.set("Neural Defend Inc")
                        url.set("https://neuraldefend.com")
                    }
                    scm {
                        url.set("https://github.com/Neural-Defend/NeuralDefend-SDKs")
                        connection.set("scm:git:https://github.com/Neural-Defend/NeuralDefend-SDKs.git")
                        developerConnection.set("scm:git:ssh://git@github.com/Neural-Defend/NeuralDefend-SDKs.git")
                    }
                    issueManagement {
                        system.set("GitHub")
                        url.set("https://github.com/Neural-Defend/NeuralDefend-SDKs/issues")
                    }
                }
            }
        }
    }

    pluginManager.withPlugin("signing") {
        val signingKey = providers.environmentVariable("SIGNING_KEY").orNull
        val signingPassword = providers.environmentVariable("SIGNING_PASSWORD").orNull
        val requireSigning = providers.gradleProperty("neuraldefend.requireSigning").orNull == "true"
        extensions.configure<SigningExtension> {
            isRequired = requireSigning
            if (!signingKey.isNullOrBlank()) {
                useInMemoryPgpKeys(signingKey, signingPassword.orEmpty())
            }
            if (!signingKey.isNullOrBlank() || requireSigning) {
                sign(extensions.getByType<PublishingExtension>().publications)
            }
        }
    }
}

tasks.register<Delete>("cleanStagingRepository") {
    delete(stagingRepository)
}

subprojects {
    tasks.withType<PublishToMavenRepository>().configureEach { mustRunAfter(":cleanStagingRepository") }
}

// Maven Central Portal upload bundle: every published file plus signatures and checksums,
// laid out as a Maven repository. maven-metadata.xml is generated by Central itself.
tasks.register<Zip>("centralBundle") {
    group = "publishing"
    description = "Publishes every library to build/staging-deploy and zips it for the Central Portal."
    val publishTasks = subprojects
        .filter { it.name.startsWith("neuraldefend") }
        .map { "${it.path}:publishAllPublicationsToStagingRepository" }
    dependsOn("cleanStagingRepository")
    dependsOn(publishTasks)
    from(stagingRepository)
    exclude("**/maven-metadata.xml*")
    archiveFileName.set("central-bundle-$sdkVersion.zip")
    destinationDirectory.set(layout.buildDirectory.dir("central"))
}
